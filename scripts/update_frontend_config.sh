#!/usr/bin/env bash
# Writes frontend/config.js from a deployed CloudFormation stack's outputs.
# Usage: scripts/update_frontend_config.sh [stack-name] (default: carely-dev)
set -euo pipefail

STACK="${1:-carely-dev}"
OUT="frontend/config.js"

API_URL=$(aws cloudformation describe-stacks --stack-name "$STACK" \
  --query "Stacks[0].Outputs[?OutputKey=='ApiUrl'].OutputValue" --output text)
REGION=$(aws cloudformation describe-stacks --stack-name "$STACK" \
  --query "Stacks[0].Outputs[?OutputKey=='Region'].OutputValue" --output text)
POOL_ID=$(aws cloudformation describe-stacks --stack-name "$STACK" \
  --query "Stacks[0].Outputs[?OutputKey=='CognitoUserPoolId'].OutputValue" --output text)
CLIENT_ID=$(aws cloudformation describe-stacks --stack-name "$STACK" \
  --query "Stacks[0].Outputs[?OutputKey=='CognitoUserPoolClientId'].OutputValue" --output text)

cat > "$OUT" <<EOF
/* GENERATED by scripts/update_frontend_config.sh — do not commit real values. */
window.CARELY_CONFIG = {
  apiUrl: '${API_URL}',
  region: '${REGION}',
  userPoolId: '${POOL_ID}',
  userPoolClientId: '${CLIENT_ID}',
};
EOF

echo "Wrote $OUT"
echo "  apiUrl:   ${API_URL}"
echo "  region:   ${REGION}"
echo "  pool:     ${POOL_ID}"
echo "  client:   ${CLIENT_ID}"
